import      { spawnSync                       } from "node:child_process" ;
import      { readFileSync                    } from "node:fs"            ;
import      { isAbsolute, join                } from "node:path"          ;
import      { userDataRoot                    } from "@/common/project-config.ts" ;
import      { displayWidth                    } from "@/common/display-width.ts"  ;
import      { writeTextAtomically             } from "@/common/mode.ts"   ;
import      { resolveMode, type Mode          } from "@/common/mode.ts"   ;
import      { compareVersions, readUpdateCache } from "@/common/update.ts" ;

/**
 * One status-line segment, never more than one line: the removed HUD grew to four lines. BoxBox does not own the host's
 * status line; `--wrap` runs the user's existing command and appends the segment to its first line, like a starship or
 * ccstatusline custom module. It never probes the network; it reads the update cache the session hook keeps.
 */
const COLORS: Record<Mode, string> = {
	off      : "\x1b[90m" ,
	check    : "\x1b[36m" ,
	align    : "\x1b[32m" ,
	refactor : "\x1b[35m" ,
};
const RESET = "\x1b[0m";

export function segment(mode: Mode, current: string, latest: string | undefined, color: boolean): string {
	const arrow = latest !== undefined && compareVersions(latest, current) > 0 ? " ↑" : "" ;
	const text  = `▣ BB·${mode.toUpperCase()}${arrow}`                                     ;
	return color ? `${COLORS[mode]}${text}${RESET}` : text;
}

/** Keeps only the first line and strips a trailing line break so the host never gets a second row. */
export const firstLine = (text: string): string => text.split(/\r?\n/u).find(line => line.trim() !== "") ?? "";

/**
 * Columns kept free at the right edge. `▣`, `·` and `↑` are East Asian ambiguous and draw two columns wide in some
 * terminals (Korean locales among them); one spare column per glyph plus one keeps the row from wrapping.
 */
export const RIGHT_MARGIN = 4;

const visible = (text: string): number => displayWidth(text.replaceAll(/\x1b\[[0-9;]*m/gu, ""));

/**
 * Lays the row out for a terminal of `columns`: the wrapped command's text on the left, BoxBox pushed to the right edge.
 * Without a usable width (or with `--left`) it falls back to `left │ mine`. The result never exceeds one row.
 */
export function compose(theirs: string, mine: string, columns: number | undefined, left = false): string {
	if (left || columns === undefined || !Number.isFinite(columns) || columns <= 0) return theirs ? `${theirs} │ ${mine}` : mine;
	const gap = columns - RIGHT_MARGIN - visible(theirs) - visible(mine);
	if (gap < 1) return theirs ? `${theirs} ${mine}` : mine;
	// Claude Code trims leading ASCII spaces from status-line output; no-break spaces keep the padding.
	return `${theirs}${"\u00a0".repeat(gap)}${mine}`;
}

/**
 * A version-free launcher for the host's `statusLine` setting. The installed plugin lives in a versioned folder, so a
 * setting that names it breaks on the next update; this shim looks the current install up in Claude's plugin registry
 * on every call. `boxbox update` rewrites it, and `boxbox statusline --install-shim` writes it once.
 */
export const SHIM = `// Generated by BoxBox. Runs the currently installed BoxBox status line; prints nothing when BoxBox is not installed.
import { spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
const registry = join(process.env.CLAUDE_CONFIG_DIR || join(homedir(), ".claude"), "plugins", "installed_plugins.json");
let root;
try { root = JSON.parse(readFileSync(registry, "utf8")).plugins?.["boxbox@boxbox-plugins"]?.[0]?.installPath; } catch {}
if (root) {
	let input = "";
	try { input = readFileSync(0, "utf8"); } catch {}
	const run = spawnSync(process.execPath, [join(root, "scripts", "boxbox.mjs"), "statusline", ...process.argv.slice(2)], { input, encoding: "utf8", windowsHide: true, timeout: 8000 });
	process.stdout.write(run.stdout ?? "");
}
`;

export const shimPath = (): string => join(userDataRoot(), "bin", "statusline.mjs");

export function installShim(): string {
	writeTextAtomically(shimPath(), SHIM);
	return shimPath();
}

/** `boxbox statusline [--wrap "<command>"] [--no-color] [--left] | --install-shim`; the host's JSON arrives on stdin and is passed through. */
export function runStatusline(args: readonly string[], current: string): number {
	if (args.includes("--install-shim")) {
		const path = installShim();
		console.log(`statusLine command: node "${path.replaceAll("\\", "/")}"`);
		return 0;
	}
	let input = "";
	try { input = readFileSync(0, "utf8"); } catch { /* no stdin when run by hand */ }
	let cwd: string | undefined;
	try {
		const value = JSON.parse(input || "{}")                 ;
		const dir   = value.workspace?.current_dir ?? value.cwd ;
		if (typeof dir === "string" && isAbsolute(dir)) cwd = dir;
	} catch { /* a malformed host payload still gets the global mode */ }
	const color   = !args.includes("--no-color") && !process.env.NO_COLOR                               ;
	const mine    = segment(resolveMode(cwd), current, readUpdateCache().latest, color)                 ;
	const at      = args.indexOf("--wrap")                                                              ;
	const wrap    = at >= 0 ? args[at + 1] : undefined                                                  ;
	const columns = process.env.COLUMNS ? Number(process.env.COLUMNS) : undefined                       ;
	const layout  = (theirs: string): string => compose(theirs, mine, columns, args.includes("--left")) ;
	if (!wrap) { process.stdout.write(layout("")); return 0; }
	// Claude Code runs status-line commands with bash (Git Bash on Windows), so the wrapped command is bash syntax;
	// cmd.exe is only the fallback when no bash is on PATH.
	const options = { input, encoding: "utf8" as const, timeout: 5_000, windowsHide: true } ;
	const bash    = spawnSync("bash", ["-c", wrap], options)                                ;
	const result  = bash.error ? spawnSync(wrap, { ...options, shell: true }) : bash        ;
	const theirs  = result.status === 0 ? firstLine(result.stdout) : ""                     ;
	process.stdout.write(layout(theirs));
	return 0;
}
